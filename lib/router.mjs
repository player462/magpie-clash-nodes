// Spin up a *separate* mihomo instance whose `listeners` each bind one
// Clash node to its own local HTTP proxy port. The user's main Clash Party
// instance (7890, tray, TUN, system proxy) is left completely untouched.
//
//   http://127.0.0.1:18001 -> node A
//   http://127.0.0.1:18002 -> node B
//   ...
// magpie accepts exactly these addresses as a provider's / account's proxy.
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import http from 'node:http';
import net from 'node:net';
import { spawn, execFileSync } from 'node:child_process';

export const DEFAULT_BASE_PORT = 18001;
export const DEFAULT_CONTROLLER_PORT = 19090;

const EXE_CANDIDATES = [
  process.env.MIHOMO_EXE,
  'D:\\clash\\Clash Party\\resources\\sidecar\\mihomo.exe',
  'C:\\Program Files\\Clash Verge\\resources\\sidecar\\mihomo.exe',
  path.join(os.homedir(), 'AppData', 'Local', 'Programs', 'Clash Verge', 'resources', 'sidecar', 'mihomo.exe'),
  '/usr/local/bin/mihomo', '/usr/bin/mihomo', '/opt/homebrew/bin/mihomo',
].filter(Boolean);

const MAIN_CONFIG_CANDIDATES = [
  process.env.MIHOMO_CONFIG,
  path.join(os.homedir(), 'AppData', 'Roaming', 'mihomo-party', 'work', 'config.yaml'),
  path.join(os.homedir(), 'AppData', 'Roaming', 'mihomo-party', 'config.yaml'),
  path.join(os.homedir(), '.config', 'mihomo', 'config.yaml'),
  path.join(os.homedir(), '.config', 'clash', 'config.yaml'),
].filter(Boolean);

export function stateDir() {
  return path.join(os.homedir(), '.config', 'magpie', 'clash-nodes');
}
export function statePath() { return path.join(stateDir(), 'router.json'); }
export function configPath() { return path.join(stateDir(), 'config.yaml'); }

export function findExe() {
  for (const p of EXE_CANDIDATES) { try { if (fs.statSync(p).isFile()) return p; } catch {} }
  return null;
}
export function findMainConfig() {
  for (const p of MAIN_CONFIG_CANDIDATES) { try { if (fs.statSync(p).isFile()) return p; } catch {} }
  return null;
}

/** Split a YAML file into top-level sections (indentation-based, no parser needed). */
export function splitSections(text) {
  const sections = new Map();
  let cur = null;
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^([A-Za-z][A-Za-z0-9_-]*):/);
    if (m) { cur = m[1]; sections.set(cur, []); }
    if (cur) sections.get(cur).push(line);
  }
  return sections;
}

function yamlString(s) {
  // JSON strings are valid YAML double-quoted scalars.
  return JSON.stringify(String(s));
}

/** Build a standalone mihomo config exposing one HTTP port per node. */
export function buildConfig(mainText, nodes, opts = {}) {
  const basePort = opts.basePort ?? DEFAULT_BASE_PORT;
  const controllerPort = opts.controllerPort ?? DEFAULT_CONTROLLER_PORT;
  const mapping = opts.mapping || portMapping(nodes, basePort);
  const sections = splitSections(mainText);
  const proxies = sections.get('proxies');
  const groups = sections.get('proxy-groups');
  if (!proxies?.length) throw new Error('主配置里没有 proxies 段，无法生成节点端口配置');

  const head = [
    '# generated by @yg/magpie-clash-nodes — one listener per Clash node',
    'mixed-port: 0', 'port: 0', 'socks-port: 0', 'redir-port: 0', 'tproxy-port: 0',
    'allow-lan: false', 'bind-address: "127.0.0.1"', 'mode: direct', 'log-level: warning',
    'ipv6: false', `external-controller: 127.0.0.1:${controllerPort}`,
    'dns:', '  enable: false',
    'tun:', '  enable: false',
    'profile:', '  store-selected: false',
  ];
  const listeners = ['listeners:'];
  nodes.forEach((n, i) => {
    listeners.push(
      `  - name: node-${i}`,
      '    type: http',
      `    port: ${mapping[n] ?? basePort + i}`,
      '    listen: 127.0.0.1',
      `    proxy: ${yamlString(n)}`,
    );
  });
  return [...head, ...proxies, ...(groups || []), ...listeners, ''].join('\n');
}

/** Stable port assignment: node name -> port. */
export function portMapping(nodes, basePort = DEFAULT_BASE_PORT) {
  const mapping = {};
  nodes.forEach((n, i) => { mapping[n] = basePort + i; });
  return mapping;
}

// Node -> port must not move when the pool is re-ordered or rebuilt: account
// proxies in providers.json are plain URLs, so a shifted port would silently
// send an account through a different node.
export function portsPath() { return path.join(stateDir(), 'ports.json'); }
function readPorts() {
  try { return JSON.parse(fs.readFileSync(portsPath(), 'utf8')) || {}; } catch { return {}; }
}
export function stablePortMapping(nodes, basePort = DEFAULT_BASE_PORT) {
  const prev = readPorts();
  const used = new Set();
  const mapping = {};
  for (const n of nodes) {
    const p = Number(prev[n]);
    if (Number.isInteger(p) && p >= basePort && p < basePort + 500 && !used.has(p)) {
      mapping[n] = p; used.add(p);
    }
  }
  let next = basePort;
  for (const n of nodes) {
    if (mapping[n]) continue;
    while (used.has(next)) next++;
    mapping[n] = next; used.add(next);
  }
  const merged = { ...prev, ...mapping };
  try {
    fs.mkdirSync(stateDir(), { recursive: true });
    fs.writeFileSync(portsPath(), JSON.stringify(merged, null, 2));
  } catch { /* best effort */ }
  return mapping;
}

function readState() {
  try { return JSON.parse(fs.readFileSync(statePath(), 'utf8')); } catch { return null; }
}
function writeState(s) {
  fs.mkdirSync(stateDir(), { recursive: true });
  fs.writeFileSync(statePath(), JSON.stringify(s, null, 2));
}

/** Try an HTTP proxy port with a plain proxy request. */
export function checkPort(port, timeout = 6000) {
  return new Promise((resolve) => {
    const req = http.request({
      host: '127.0.0.1', port, method: 'GET',
      path: 'http://www.gstatic.com/generate_204',
      headers: { Host: 'www.gstatic.com' },
      timeout,
    }, (res) => {
      res.resume();
      resolve({ ok: res.statusCode === 204 || res.statusCode === 200, status: res.statusCode });
    });
    req.on('timeout', () => { req.destroy(); resolve({ ok: false, status: 'timeout' }); });
    req.on('error', (e) => resolve({ ok: false, status: e.code || e.message }));
    req.end();
  });
}

function portOpen(port, timeout = 1500) {
  return new Promise((resolve) => {
    const s = net.connect({ host: '127.0.0.1', port });
    const t = setTimeout(() => { s.destroy(); resolve(false); }, timeout);
    s.on('connect', () => { clearTimeout(t); s.destroy(); resolve(true); });
    s.on('error', () => { clearTimeout(t); resolve(false); });
  });
}
export { portOpen as portListening };

/** True when the process holding `pid` no longer exists. */
async function waitForPidGone(pid, ms = 8000) {
  const start = Date.now();
  for (;;) {
    let alive = false;
    try { process.kill(pid, 0); alive = true; } catch { alive = false; }
    if (!alive) return true;
    if (Date.now() - start > ms) return false;
    await new Promise((r) => setTimeout(r, 200));
  }
}

/**
 * Liveness of the recorded instance: the pid must exist AND its controller
 * port must answer. The state file alone lies when the spawned mihomo died
 * (a stop/start race, a crash), while magpie keeps aiming at its ports.
 */
export async function instanceAlive() {
  const s = readState();
  if (!s?.pid) return false;
  try { process.kill(s.pid, 0); } catch { return false; }
  return await portOpen(s.controllerPort, 800);
}

function waitForController(port, ms = 12000) {
  const start = Date.now();
  return (async () => {
    for (;;) {
      if (await portOpen(port, 800)) return true;
      if (Date.now() - start > ms) return false;
      await new Promise((r) => setTimeout(r, 300));
    }
  })();
}

/** Start the per-node listener instance. Returns the state object. */
export async function startRouter(nodes, opts = {}) {
  const exe = opts.exe || findExe();
  if (!exe) throw new Error('找不到 mihomo.exe（设置 MIHOMO_EXE 指向它）');
  const mainConfig = opts.mainConfig || findMainConfig();
  if (!mainConfig) throw new Error('找不到 Clash 主配置（设置 MIHOMO_CONFIG）');
  const basePort = opts.basePort ?? DEFAULT_BASE_PORT;
  const controllerPort = opts.controllerPort ?? DEFAULT_CONTROLLER_PORT;

  const prev = readState();
  if (prev?.pid) {
    await stopRouter({ quiet: true }).catch(() => {});
    // A fresh spawn that races the dying predecessor loses the bind and
    // exits silently, leaving magpie aimed at dead ports — wait it out.
    await waitForPidGone(prev.pid, 8000);
  }

  const text = fs.readFileSync(mainConfig, 'utf8');
  const mapping = stablePortMapping(nodes, basePort);
  const cfg = buildConfig(text, nodes, { basePort, controllerPort, mapping });
  fs.mkdirSync(stateDir(), { recursive: true });
  fs.writeFileSync(configPath(), cfg);

  const child = spawn(exe, ['-d', stateDir(), '-f', configPath()], {
    detached: true, stdio: 'ignore', windowsHide: true,
  });
  child.unref();

  const up = await waitForController(controllerPort);
  if (!up) {
    // The process may still be alive but failed to bind; report honestly.
    const port0 = await portOpen(basePort, 1000);
    if (!port0) throw new Error(`mihomo 起来了但控制器 ${controllerPort} 或节点端口 ${basePort} 未监听，检查 ${configPath()}`);
  }

  const ports = {};
  for (const [name, port] of Object.entries(mapping)) ports[name] = await portOpen(port, 1200);
  const state = {
    pid: child.pid, exe, mainConfig, basePort, controllerPort,
    nodes: nodes.slice(), mapping, ports,
    startedAt: new Date().toISOString(),
  };
  writeState(state);
  return state;
}

export async function stopRouter(opts = {}) {
  const s = readState();
  if (!s?.pid) { if (!opts.quiet) throw new Error('没有运行中的节点实例'); return null; }
  if (process.platform === 'win32') {
    try { execFileSync('taskkill', ['/PID', String(s.pid), '/T', '/F'], { stdio: 'ignore', timeout: 8000 }); }
    catch { /* already gone */ }
  } else {
    try { process.kill(s.pid, 'SIGTERM'); } catch { /* already gone */ }
  }
  try { fs.unlinkSync(statePath()); } catch {}
  return s;
}

export function routerStatus() {
  const s = readState();
  if (!s) return { running: false };
  // Seed the stable port table from an instance started before it existed,
  // so a later rebuild keeps every node on the port an account points at.
  try {
    if (!Object.keys(readPorts()).length && s.mapping && Object.keys(s.mapping).length) {
      fs.writeFileSync(portsPath(), JSON.stringify(s.mapping, null, 2));
    }
  } catch { /* best effort */ }
  return { running: true, ...s, proxyUrls: Object.fromEntries(
    Object.entries(s.mapping || {}).map(([n, p]) => [n, `http://127.0.0.1:${p}`]),
  ) };
}
