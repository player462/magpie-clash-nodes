// Spin up a *separate* mihomo instance whose `listeners` each bind one
// Clash node to its own local HTTP proxy port. The user's main Clash Party
// instance (7890, tray, TUN, system proxy) is left completely untouched.
//
//   http://127.0.0.1:18001 -> node A
//   http://127.0.0.1:18002 -> node B
//   ...
// magpie accepts exactly these addresses as a provider's / account's proxy.
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import http from 'node:http';
import net from 'node:net';
import { spawn, spawnSync } from 'node:child_process';
import { request } from './pipe.mjs';
import { normalizeProxyBlock } from './profiles.mjs';

export const DEFAULT_BASE_PORT = 18001;
export const DEFAULT_CONTROLLER_PORT = 19090;

const EXE_CANDIDATES = [
  process.env.MIHOMO_EXE,
  'D:\\clash\\Clash Party\\resources\\sidecar\\mihomo.exe',
  'C:\\Program Files\\Clash Verge\\resources\\sidecar\\mihomo.exe',
  path.join(os.homedir(), 'AppData', 'Local', 'Programs', 'Clash Verge', 'resources', 'sidecar', 'mihomo.exe'),
  '/usr/local/bin/mihomo', '/usr/bin/mihomo', '/opt/homebrew/bin/mihomo',
].filter(Boolean);

const MAIN_CONFIG_CANDIDATES = [
  process.env.MIHOMO_CONFIG,
  path.join(os.homedir(), 'AppData', 'Roaming', 'mihomo-party', 'work', 'config.yaml'),
  path.join(os.homedir(), 'AppData', 'Roaming', 'mihomo-party', 'config.yaml'),
  path.join(os.homedir(), '.config', 'mihomo', 'config.yaml'),
  path.join(os.homedir(), '.config', 'clash', 'config.yaml'),
].filter(Boolean);

export function stateDir() {
  return path.join(os.homedir(), '.config', 'magpie', 'clash-nodes');
}
export function statePath() { return path.join(stateDir(), 'router.json'); }
export function configPath() { return path.join(stateDir(), 'config.yaml'); }

export function findExe() {
  for (const p of EXE_CANDIDATES) { try { if (fs.statSync(p).isFile()) return p; } catch {} }
  return null;
}
export function findMainConfig() {
  for (const p of MAIN_CONFIG_CANDIDATES) { try { if (fs.statSync(p).isFile()) return p; } catch {} }
  return null;
}

/** Split a YAML file into top-level sections (indentation-based, no parser needed). */
export function splitSections(text) {
  const sections = new Map();
  let cur = null;
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^([A-Za-z][A-Za-z0-9_-]*):/);
    if (m) { cur = m[1]; sections.set(cur, []); }
    if (cur) sections.get(cur).push(line);
  }
  return sections;
}

function yamlString(s) {
  // JSON strings are valid YAML double-quoted scalars.
  return JSON.stringify(String(s));
}

/** Build a standalone mihomo config exposing one HTTP port per node.
 *  `opts.proxyBlocks` replaces the `proxies:` section (multi-subscription merge). */
export function buildConfig(mainText, nodes, opts = {}) {
  const basePort = opts.basePort ?? DEFAULT_BASE_PORT;
  const controllerPort = opts.controllerPort ?? DEFAULT_CONTROLLER_PORT;
  const mapping = opts.mapping || portMapping(nodes, basePort);
  const sections = splitSections(mainText);
  const blocks = opts.proxyBlocks?.length
    ? opts.proxyBlocks.map((b) => normalizeProxyBlock(b)).filter(Boolean)
    : null;
  const proxies = blocks?.length
    ? ['proxies:', ...blocks]
    : sections.get('proxies');
  const groups = blocks?.length ? [] : sections.get('proxy-groups');
  if (!proxies?.length) throw new Error('主配置里没有 proxies 段，无法生成节点端口配置');

  // Own plain-IP DNS + physical-NIC binding keep this instance working even
  // when the main Clash app runs TUN (虚拟网卡) mode: without them the TUN
  // would capture our outbound, its fake-ip DNS would poison proxy-server
  // lookups, and every node port would time out.
  const dnsLines = [
    'dns:',
    '  enable: true',
    '  ipv6: false',
    '  enhanced-mode: redir-host',
    '  nameserver:',
    '    - 223.5.5.5',
    '    - 119.29.29.29',
    '    - 8.8.8.8',
  ];
  const head = [
    '# generated by @yg/magpie-clash-nodes — one listener per Clash node',
    'mixed-port: 0', 'port: 0', 'socks-port: 0', 'redir-port: 0', 'tproxy-port: 0',
    'allow-lan: false', 'bind-address: "127.0.0.1"', 'mode: direct', 'log-level: warning',
    'ipv6: false', `external-controller: 127.0.0.1:${controllerPort}`,
    ...dnsLines,
    ...(opts.interfaceName ? [`interface-name: ${yamlString(opts.interfaceName)}`] : []),
    'tun:', '  enable: false',
    'profile:', '  store-selected: false',
  ];
  const listeners = ['listeners:'];
  nodes.forEach((n, i) => {
    listeners.push(
      `  - name: node-${i}`,
      '    type: http',
      `    port: ${mapping[n] ?? basePort + i}`,
      '    listen: 127.0.0.1',
      `    proxy: ${yamlString(n)}`,
    );
  });
  return [...head, ...proxies, ...(groups || []), ...listeners, ''].join('\n');
}

/** Stable port assignment: node name -> port. */
export function portMapping(nodes, basePort = DEFAULT_BASE_PORT) {
  const mapping = {};
  nodes.forEach((n, i) => { mapping[n] = basePort + i; });
  return mapping;
}

// Node -> port must not move when the pool is re-ordered or rebuilt: account
// proxies in providers.json are plain URLs, so a shifted port would silently
// send an account through a different node.
export function portsPath() { return path.join(stateDir(), 'ports.json'); }
function readPorts() {
  try { return JSON.parse(fs.readFileSync(portsPath(), 'utf8')) || {}; } catch { return {}; }
}
function referencedProxyPorts() {
  // Never hand a port already written into magpie's providers.json to a
  // different node: a vanished subscription node must not be silently
  // replaced by whatever new node happens to be next in the list.
  const dir = process.env.MAGPIE_CONFIG_DIR || path.join(os.homedir(), '.config', 'magpie');
  const out = new Set();
  try {
    const text = fs.readFileSync(path.join(dir, 'providers.json'), 'utf8');
    for (const m of text.matchAll(/127\.0\.0\.1:(\d+)/g)) out.add(Number(m[1]));
  } catch { /* magpie not installed yet */ }
  return out;
}
export function stablePortMapping(nodes, basePort = DEFAULT_BASE_PORT) {
  const prev = readPorts();
  const reserved = referencedProxyPorts();
  const used = new Set();
  const mapping = {};
  for (const n of nodes) {
    const p = Number(prev[n]);
    if (Number.isInteger(p) && p >= basePort && p < basePort + 2000 && !used.has(p)) {
      mapping[n] = p; used.add(p);
    }
  }
  let next = basePort;
  for (const n of nodes) {
    if (mapping[n]) continue;
    while (used.has(next) || reserved.has(next)) next++;
    mapping[n] = next; used.add(next);
  }
  const merged = { ...prev, ...mapping };
  try {
    fs.mkdirSync(stateDir(), { recursive: true });
    fs.writeFileSync(portsPath(), JSON.stringify(merged, null, 2));
  } catch { /* best effort */ }
  return mapping;
}

function readState() {
  try { return JSON.parse(fs.readFileSync(statePath(), 'utf8')); } catch { return null; }
}
function writeState(s) {
  fs.mkdirSync(stateDir(), { recursive: true });
  fs.writeFileSync(statePath(), JSON.stringify(s, null, 2));
}

/** Try an HTTP proxy port with a plain proxy request. */
export function checkPort(port, timeout = 6000) {
  return new Promise((resolve) => {
    const req = http.request({
      host: '127.0.0.1', port, method: 'GET',
      path: 'http://www.gstatic.com/generate_204',
      headers: { Host: 'www.gstatic.com' },
      timeout,
    }, (res) => {
      res.resume();
      resolve({ ok: res.statusCode === 204 || res.statusCode === 200, status: res.statusCode });
    });
    req.on('timeout', () => { req.destroy(); resolve({ ok: false, status: 'timeout' }); });
    req.on('error', (e) => resolve({ ok: false, status: e.code || e.message }));
    req.end();
  });
}

function portOpen(port, timeout = 1500) {
  return new Promise((resolve) => {
    const s = net.connect({ host: '127.0.0.1', port });
    const t = setTimeout(() => { s.destroy(); resolve(false); }, timeout);
    s.on('connect', () => { clearTimeout(t); s.destroy(); resolve(true); });
    s.on('error', () => { clearTimeout(t); resolve(false); });
  });
}
export { portOpen as portListening };

/** True when the process holding `pid` no longer exists. */
async function waitForPidGone(pid, ms = 8000) {
  const start = Date.now();
  for (;;) {
    let alive = false;
    try { process.kill(pid, 0); alive = true; } catch { alive = false; }
    if (!alive) return true;
    if (Date.now() - start > ms) return false;
    await new Promise((r) => setTimeout(r, 200));
  }
}

/**
 * Liveness of the recorded instance: the pid must exist AND its controller
 * port must answer. The state file alone lies when the spawned mihomo died
 * (a stop/start race, a crash), while magpie keeps aiming at its ports.
 */
export async function instanceAlive() {
  const s = readState();
  if (!s) return false;
  // pid can be unknown (router.pid never written); the controller port alone
  // is still a valid liveness signal in that case.
  if (s.pid) {
    try { process.kill(s.pid, 0); } catch { return false; }
  }
  return await portOpen(s.controllerPort, 800);
}

function waitForController(port, ms = 12000) {
  const start = Date.now();
  return (async () => {
    for (;;) {
      if (await portOpen(port, 800)) return true;
      if (Date.now() - start > ms) return false;
      await new Promise((r) => setTimeout(r, 300));
    }
  })();
}

/** Start the per-node listener instance. Returns the state object. */
function readLogTail(file, lines = 8) {
  try {
    const text = fs.readFileSync(file, 'utf8').trim();
    return text.split(/\r?\n/).slice(-lines).join(' | ');
  } catch { return ''; }
}

function spawnSyncText(cmd, argv, opts = {}) {
  const r = spawnSync(cmd, argv, { windowsHide: true, timeout: 25000, ...opts });
  const s = (v) => (v == null ? '' : typeof v === 'string' ? v : Buffer.from(v).toString('utf8'));
  return { status: r.status, stdout: s(r.stdout), stderr: s(r.stderr), error: r.error };
}

// VBS launcher. Two-stage, both stages guaranteed invisible:
//   host spawns wscript (GUI subsystem — never allocates a console)
//   stage 1 creates wscript#2 through WMI — WmiPrvSE is its parent, so the
//     whole tree escapes magpie's kill-on-close job object
//   stage 2 runs `cmd /c mihomo … > log` with shell Run(…, 0) — SW_HIDE is
//     applied by CreateProcess itself, so no console window can flash
//   stage 2 then polls WMI for the mihomo pid (matched by our config path)
//     and records it in router.pid for liveness checks and stopping
function vbsStr(s) { return '"' + String(s).replace(/"/g, '""') + '"'; }

function writeLaunchVbs(file, exe, args, logFile, pidFile, marker, workDir) {
  const inner = [vbsStr(exe), ...args.map(vbsStr), '>', vbsStr(logFile), '2>&1'].join(' ');
  const cmdLiteral = vbsStr(`cmd.exe /c "${inner}"`);
  const script = [
    "Option Explicit",
    "Dim wmi, sh, fso, startup, rc, pidOut, i, p, cmd",
    'Set wmi = GetObject("winmgmts:{impersonationLevel=impersonate}!\\\\.\\root\\cimv2")',
    "If WScript.Arguments.Count() = 0 Then WScript.Quit 87",
    "If WScript.Arguments(0) = \"1\" Then",
    "  Set startup = wmi.Get(\"Win32_ProcessStartup\").SpawnInstance_()",
    "  startup.ShowWindow = 0",
    '  rc = wmi.Get("Win32_Process").Create("wscript.exe """ & WScript.ScriptFullName & """ run", Null, startup, pidOut)',
    "  WScript.Quit rc",
    "End If",
    'Set sh = CreateObject("WScript.Shell")',
    'Set fso = CreateObject("Scripting.FileSystemObject")',
    `cmd = ${cmdLiteral}`,
    `sh.Run cmd, 0, False`,
    `For i = 1 To 80`,
    "  WScript.Sleep 250",
    "  For Each p In wmi.ExecQuery(\"SELECT ProcessId, CommandLine FROM Win32_Process WHERE Name='mihomo.exe'\")",
    `    If InStr(1, p.CommandLine & "", ${vbsStr(marker)}, vbTextCompare) > 0 Then`,
    `      fso.CreateTextFile(${vbsStr(pidFile)}, True).Write CStr(p.ProcessId)`,
    "      WScript.Quit 0",
    "    End If",
    "  Next",
    "Next",
    "",
  ].join('\r\n');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  // wscript honours a UTF-16 BOM, so non-ASCII install paths survive too
  fs.writeFileSync(file, Buffer.from('\uFEFF' + script, 'utf16le'));
  return file;
}

function findRouterPidByPS(configPath) {
  const out = spawnSyncText('powershell.exe', [
    '-NoProfile', '-NonInteractive', '-Command',
    `[Console]::OutputEncoding=[System.Text.Encoding]::UTF8; Get-CimInstance Win32_Process -Filter "Name='mihomo.exe'" | ` +
    `Where-Object { $_.CommandLine -like '*${configPath.replace(/'/g, "''")}*' } | ` +
    'Select-Object -First 1 -ExpandProperty ProcessId',
  ], { timeout: 15000 });
  const n = Number(out.stdout.trim().split(/\r?\n/)[0]);
  return Number.isInteger(n) && n > 0 ? n : 0;
}

async function waitForRouterPid(pidFile, configPath, ms = 10000) {
  const start = Date.now();
  for (;;) {
    try {
      const n = Number(fs.readFileSync(pidFile, 'utf8').trim());
      if (Number.isInteger(n) && n > 0) return n;
    } catch { /* not written yet */ }
    if (Date.now() - start > ms) break;
    await new Promise((r) => setTimeout(r, 250));
  }
  return findRouterPidByPS(configPath);
}

// Outbound NIC of this instance. With the main Clash in TUN mode the virtual
// adapter grabs the default route with the lowest metric, and virtual NICs
// (Radmin VPN etc.) can sort first by InterfaceMetric — so resolve the
// default-route table against Get-NetAdapter -Physical (TUN adapters are
// never "physical") before falling back to a name filter.
const TUN_IF_RE = /(mihomo|clash|meta|sing|tun|tap|wintun|wireguard|loopback|虚拟|回环|vmware|virtualbox|hyper-v|vethernet|bluestacks|vpn|radmin|zerotier|tailscale|openvpn|hamachi|vgate|utun)/i;
let ifCache = { at: 0, name: '' };

const PHYS_ROUTE_PS =
  '[Console]::OutputEncoding=[System.Text.Encoding]::UTF8; ' +
  '$p=@{}; Get-NetAdapter -Physical -ErrorAction SilentlyContinue | ForEach-Object { $p[[int]$_.ifIndex] = $_.Name }; ' +
  'Get-NetRoute -DestinationPrefix \'0.0.0.0/0\' -AddressFamily IPv4 -ErrorAction SilentlyContinue | ' +
  'Sort-Object { $_.RouteMetric + $_.InterfaceMetric } | ' +
  'ForEach-Object { if ($p.ContainsKey([int]$_.InterfaceIndex)) { $p[[int]$_.InterfaceIndex]; break } }';

export function detectInterface(maxAgeMs = 300000) {
  if (process.platform !== 'win32') return '';
  const t = Date.now();
  if (ifCache.at && t - ifCache.at < maxAgeMs) return ifCache.name;
  let name = '';
  try {
    const out = spawnSyncText('powershell.exe', [
      '-NoProfile', '-NonInteractive', '-Command', PHYS_ROUTE_PS,
    ], { timeout: 15000 });
    name = out.stdout.split(/\r?\n/).map((s) => s.trim()).filter(Boolean)[0] || '';
  } catch { /* keep '' */ }
  if (!name) {
    try {
      const out = spawnSyncText('powershell.exe', [
        '-NoProfile', '-NonInteractive', '-Command',
        '[Console]::OutputEncoding=[System.Text.Encoding]::UTF8; Get-NetIPInterface -AddressFamily IPv4 -ConnectionState Connected -ErrorAction SilentlyContinue | Sort-Object InterfaceMetric | ForEach-Object { $_.InterfaceAlias }',
      ], { timeout: 15000 });
      for (const line of out.stdout.split(/\r?\n/)) {
        const s = line.trim();
        if (s && !TUN_IF_RE.test(s)) { name = s; break; }
      }
    } catch { /* keep '' */ }
  }
  if (name && TUN_IF_RE.test(name)) name = '';
  ifCache = { at: t, name };
  return name;
}

export async function startRouter(nodes, opts = {}) {
  if (!Array.isArray(nodes) || nodes.length === 0) throw new Error('没有选中任何节点，节点池为空');
  const exe = opts.exe || findExe();
  if (!exe) throw new Error('找不到 mihomo.exe（设置 MIHOMO_EXE 指向它）');
  const mainConfig = opts.mainConfig || findMainConfig();
  if (!mainConfig) throw new Error('找不到 Clash 主配置（设置 MIHOMO_CONFIG）');
  const basePort = opts.basePort ?? DEFAULT_BASE_PORT;
  const controllerPort = opts.controllerPort ?? DEFAULT_CONTROLLER_PORT;

  const prev = readState();
  if (prev) {
    await stopRouter({ quiet: true }).catch(() => {});
    // A fresh spawn that races the dying predecessor loses the bind and
    // exits silently, leaving magpie aimed at dead ports — wait it out.
    if (prev.pid) {
      await waitForPidGone(prev.pid, 8000);
    } else if (prev.controllerPort) {
      const t0 = Date.now();
      while ((await portOpen(prev.controllerPort, 400)) && Date.now() - t0 < 6000) {
        await new Promise((r) => setTimeout(r, 200));
      }
    }
  }

  const text = fs.readFileSync(mainConfig, 'utf8');
  const mapping = stablePortMapping(nodes, basePort);
  const interfaceName = opts.interfaceName !== undefined ? opts.interfaceName : detectInterface();
  const cfg = buildConfig(text, nodes, {
    basePort, controllerPort, mapping, proxyBlocks: opts.proxyBlocks, interfaceName,
  });
  fs.mkdirSync(stateDir(), { recursive: true });
  fs.writeFileSync(configPath(), cfg);

  // Validate before spawning: a merged config with bad indentation otherwise
  // dies silently and every assigned account port goes dead.
  const check = spawnSyncText(exe, ['-t', '-d', stateDir(), '-f', configPath()], { timeout: 20000 });
  if (check.status !== 0 || /test failed|configuration file.*failed/i.test(check.stdout + check.stderr)) {
    const detail = [check.stderr, check.stdout].filter(Boolean).join(' | ').trim().split(/\r?\n/).slice(-4).join(' | ');
    throw new Error(`mihomo 配置校验失败${detail ? `：${detail}` : ''}（${configPath()}）`);
  }

  const logFile = path.join(stateDir(), 'router.log');
  const pidFile = path.join(stateDir(), 'router.pid');
  try { fs.writeFileSync(logFile, ''); } catch {}
  try { fs.rmSync(pidFile, { force: true }); } catch {}

  if (process.platform === 'win32') {
    const vbsFile = path.join(stateDir(), 'router-launch.vbs');
    writeLaunchVbs(vbsFile, exe, ['-d', stateDir(), '-f', configPath()], logFile, pidFile, configPath(), stateDir());
    try { fs.unlinkSync(path.join(stateDir(), 'wmi-launch.ps1')); } catch {}
    try { fs.unlinkSync(path.join(stateDir(), 'wmi-launch.json')); } catch {}
    const wscript = path.join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'wscript.exe');
    const child = spawn(wscript, [vbsFile, '1'], { detached: true, stdio: 'ignore', windowsHide: true });
    child.unref();
  } else {
    const child = spawn(exe, ['-d', stateDir(), '-f', configPath()], { detached: true, stdio: 'ignore' });
    child.unref();
    try { fs.writeFileSync(pidFile, String(child.pid)); } catch {}
  }

  const up = await waitForController(controllerPort);
  if (!up) {
    // The process may still be alive but failed to bind; report honestly.
    const port0 = await portOpen(basePort, 1000);
    if (!port0) {
      const tail = readLogTail(logFile);
      throw new Error(`mihomo 没起来：控制器 ${controllerPort} / 节点端口 ${basePort} 未监听${tail ? `；日志：${tail}` : ''}（${configPath()}）`);
    }
  }
  const pid = await waitForRouterPid(pidFile, configPath());

  const ports = {};
  for (const [name, port] of Object.entries(mapping)) ports[name] = await portOpen(port, 1200);
  const state = {
    pid, exe, mainConfig, config: configPath(), basePort, controllerPort,
    nodes: nodes.slice(), mapping, ports,
    startedAt: new Date().toISOString(),
  };
  writeState(state);
  return state;
}

export async function stopRouter(opts = {}) {
  const s = readState();
  if (!s) { if (!opts.quiet) throw new Error('没有运行中的节点实例'); return null; }
  let pid = s.pid;
  if (!pid && s.config) {
    try { pid = findRouterPidByPS(s.config); } catch { pid = 0; }
  }
  if (pid) {
    if (process.platform === 'win32') {
      try { spawnSync('taskkill', ['/PID', String(pid), '/T', '/F'], { stdio: 'ignore', timeout: 8000, windowsHide: true }); }
      catch { /* already gone */ }
    } else {
      try { process.kill(pid, 'SIGTERM'); } catch { /* already gone */ }
    }
  }
  try { fs.unlinkSync(statePath()); } catch {}
  try { fs.unlinkSync(path.join(stateDir(), 'router.pid')); } catch {}
  return s;
}

/** Measure node latency through our own instance's controller. */
export async function testDelays(names, opts = {}) {
  const port = opts.controllerPort ?? readState()?.controllerPort ?? DEFAULT_CONTROLLER_PORT;
  const timeout = opts.timeout ?? 5000;
  const target = { kind: 'tcp', host: '127.0.0.1', port };
  const url = opts.url || 'http://www.gstatic.com/generate_204';
  const out = {};
  let i = 0;
  const worker = async () => {
    for (;;) {
      const idx = i++;
      if (idx >= names.length) return;
      const n = names[idx];
      try {
        const r = await request(target, 'GET',
          `/proxies/${encodeURIComponent(n)}/delay?timeout=${timeout}&url=${encodeURIComponent(url)}`,
          null, { timeout: timeout + 5000 });
        out[n] = typeof r.json?.delay === 'number' ? r.json.delay : null;
      } catch { out[n] = null; }
    }
  };
  const n = Math.max(1, Math.min(opts.concurrency ?? 8, names.length));
  await Promise.all(Array.from({ length: n }, worker));
  return out;
}

export function routerStatus() {  const s = readState();
  if (!s) return { running: false };
  // Seed the stable port table from an instance started before it existed,
  // so a later rebuild keeps every node on the port an account points at.
  try {
    if (!Object.keys(readPorts()).length && s.mapping && Object.keys(s.mapping).length) {
      fs.writeFileSync(portsPath(), JSON.stringify(s.mapping, null, 2));
    }
  } catch { /* best effort */ }
  return { running: true, ...s, proxyUrls: Object.fromEntries(
    Object.entries(s.mapping || {}).map(([n, p]) => [n, `http://127.0.0.1:${p}`]),
  ) };
}
